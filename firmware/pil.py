# ---------------------------------------------------------------- traces
def make_trace(scen, seed, n_steps):
    from kic_attacks import build_world, scenario
    from certify.loop import RunConfig, run
    W = make_trace.world = getattr(make_trace, "world", None) or build_world()
    prop, gstar, spoof, hist, exc = scenario(scen, seed, W)
    tr = []
    r0 = np.random.default_rng(seed + 99)
    nominal0 = [float(r0.uniform(0.1, 0.9)), float(r0.uniform(0.1, 0.9))]
    res = run(RunConfig(gate="kic_sound", n_steps=n_steps, seed=seed, excitation=exc), prop, gstar=gstar,
              spoofer=spoof, surrogate=W["sur_clean"], hist=hist, pil_trace=tr)
    return dict(scenario=scen, seed=seed, key=f"key-{seed}", nominal0=nominal0, trace=tr,
                ecost=res["ecost"])


def write_header(T, path, as_float=False):
    ty = "float" if as_float else "double"
    fmt = lambda v: repr(float(v)) + ("f" if as_float else "")
    tr = T["trace"]
    L = [f"/* generated by firmware/pil.py: {T['scenario']} seed {T['seed']} */",
         f"#define TRACE_N {len(tr)}u", f'#define TRACE_KEY "{T["key"]}"',
         f"static const double TRACE_NOMINAL0[2] = {{{T['nominal0'][0]!r}, {T['nominal0'][1]!r}}};",
         "static const signed char TRACE_PA[] = {" + ",".join(str(x["pa"]) for x in tr) + "};",
         "static const double TRACE_PV[] = {" + ",".join(repr(x["pv"]) for x in tr) + "};",
         f"static const double TRACE_EXO[][3] = {{" + ",".join("{" + ",".join(repr(v) for v in x["exo"]) + "}" for x in tr) + "};",
         "static const double TRACE_COST[] = {" + ",".join(repr(x["cost"]) for x in tr) + "};",
         "static const double TRACE_NOM[][2] = {" + ",".join("{" + ",".join(repr(v) for v in x["nominal"]) + "}" for x in tr) + "};",
         "static const double TRACE_APP[][2] = {" + ",".join("{" + ",".join(repr(v) for v in x["applied"]) + "}" for x in tr) + "};"]
    path.write_text("\n".join(L) + "\n")


# ---------------------------------------------------------------- builds
def sh(cmd):
    p = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    if p.returncode:
        raise RuntimeError(cmd + "\n" + p.stdout + p.stderr)
    return p.stdout


def build_host(hdr_dir):
    exe = BUILD / "pil_host"
    # the firmware main loops forever; for the host run a small driver instead
    drv = BUILD / "host_drv.c"
    drv.write_text(r'''
#include <stdio.h>
#include <math.h>
#include "../src/kic_gate.h"
#include "trace.h"
int main(void){ static kic_state_t G; double nom[2], app[2]; unsigned t, mism = 0, first = 0;
  kic_init(&G, TRACE_KEY, TRACE_NOMINAL0);
  for (t = 1; t <= TRACE_N; t++) { unsigned i = t - 1;
    kic_decide(&G, t, TRACE_PA[i], TRACE_PV[i], nom, app);
    if (fabs(nom[0]-TRACE_NOM[i][0])>1e-9||fabs(nom[1]-TRACE_NOM[i][1])>1e-9||fabs(app[0]-TRACE_APP[i][0])>1e-9||fabs(app[1]-TRACE_APP[i][1])>1e-9){
      if(!mism){first=t; printf("first mismatch t=%u nom %.9f %.9f vs %.9f %.9f\n",t,nom[0],nom[1],TRACE_NOM[i][0],TRACE_NOM[i][1]);}
      mism++; kic_resync(&G, TRACE_NOM[i]); }
    kic_observe(&G, t, TRACE_EXO[i], TRACE_COST[i]); }
  printf("ticks %u mismatch %u first %u resets %d overflow %d anchors %d\n", TRACE_N, mism, first, G.n_resets, G.anchor_overflow, G.n_anchors);
  return 0; }''')
    sh(f"gcc -O2 -std=c99 -I{hdr_dir} -I{FW/'src'} {drv} {FW/'src/kic_gate.c'} -lm -o {exe}")
    return sh(str(exe))


def build_fw(bk, hdr_dir, tag):
    b = BOARDS[bk]
    ld = BUILD / f"{bk}.ld"
    ld.write_text((FW / "src/link.ld.in").read_text()
                  .replace("@FLASH_ORIGIN@", hex(b["flash"][0])).replace("@FLASH_LEN@", str(b["flash"][1]))
                  .replace("@RAM_ORIGIN@", hex(b["ram"][0])).replace("@RAM_LEN@", str(b["ram"][1])))
    elf = BUILD / f"{bk}_{tag}.elf"
    start = FW / ("src/startup_cm.c" if b["arch"] == "cm" else "src/startup_rv.S")
    sh(f"{b['cc']}gcc {b['flags']} -O2 -ffunction-sections -fdata-sections -Wl,--gc-sections "
       f"-DKIC_MAX_ANCHORS=8 -nostartfiles {'-Wl,-e,_start' if b['arch'] == 'rv' else ''} -T {ld} -I{hdr_dir} -I{FW/'src'} "
       f"{start} {FW/'src/main_pil.c'} {FW/'src/kic_gate.c'} -lm -lc -lgcc -o {elf}")
    size = sh(f"{b['cc']}size -A {elf}")
    sec = {m.group(1): int(m.group(2)) for m in re.finditer(r"^(\.\w+)\s+(\d+)", size, re.M)}
    syms = {}
    for line in sh(f"{b['cc']}nm {elf}").splitlines():
        p = line.split()
        if len(p) == 3:
            syms[p[2]] = int(p[0], 16)
    sizes = {}
    for line in sh(f"{b['cc']}nm -S {elf}").splitlines():
        p = line.split()
        if len(p) == 4:
            sizes[p[3]] = int(p[1], 16)
    gate_bss = sizes.get("G", 0)
    trace_bytes = sum(v for k, v in sizes.items() if k.startswith("TRACE_"))
    return elf, sec, syms, gate_bss, trace_bytes


def run_renode(bk, elf, syms, sim_seconds):
    b = BOARDS[bk]
    log = BUILD / f"{bk}.log"
    resc = BUILD / f"{bk}.resc"
    boot = (f"cpu VectorTableOffset {hex(b['flash'][0])}" if b["arch"] == "cm"
            else f"cpu PC {hex(syms['_start'])}")
    names = ["pil_mismatch", "pil_first_mismatch", "pil_ticks", "pil_stack_bytes", "pil_overflow",
             "pil_max_anchors", "pil_resets", "pil_done"]
    reads = "\n".join(f'sysbus ReadDoubleWord {hex(syms[n])}' for n in names)
    resc.write_text(f'''mach create "dut"
machine LoadPlatformDescription @{b["repl"]}
sysbus LoadELF @{elf}
{boot}
cpu AddHook {hex(syms["tick_done"] & ~1)} "self.Log(LogLevel.Warning, 'INSN %d' % self.ExecutedInstructions)"
emulation RunFor "{sim_seconds}"
{reads}
quit
''')
    out = subprocess.run(f"./renode --disable-gui --console -e 'include @{resc}'", shell=True,
                         cwd=RENODE, capture_output=True, text=True, timeout=3600).stdout
    log.write_text(out)
    insn = [int(x) for x in re.findall(r"INSN (\d+)", out)]
    vals = re.findall(r"^(0x[0-9A-Fa-f]{8})\s*$", out, re.M)
    res = dict(zip(names, [int(v, 16) for v in vals[-len(names):]])) if len(vals) >= len(names) else {}
    return insn, res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenarios", nargs="*", default=["clean", "a1_telemetry", "spoof_blind"])
    ap.add_argument("--boards", nargs="*", default=list(BOARDS))
    ap.add_argument("--n_steps", type=int, default=800)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--sim_seconds", default="60")
    args = ap.parse_args()
    BUILD.mkdir(exist_ok=True)
    out = dict(boards={}, scenarios={})
    for scen in args.scenarios:
        T = make_trace(scen, args.seed, args.n_steps)
        hdr = BUILD / f"hdr_{scen}"
        hdr.mkdir(exist_ok=True)
        write_header(T, hdr / "trace.h")
        host = build_host(hdr)
        print(f"[{scen}] reference ecost {T['ecost']:.3f}; host C replay: {host.strip()}", flush=True)
        out["scenarios"][scen] = dict(host=host.strip(), ecost=T["ecost"])
        for bk in args.boards:
            elf, sec, syms, gate_bss, trace_bytes = build_fw(bk, hdr, scen)
            insn, res = run_renode(bk, elf, syms, args.sim_seconds)
            per = np.diff(np.array(insn, dtype=np.int64))[1:] if len(insn) > 2 else np.array([])
            b = BOARDS[bk]
            text = sec.get(".text", 0)
            row = dict(board=b["name"], core=b["core"], mhz=b["mhz"], fpu=b["fpu"],
                       ticks_executed=len(per), mismatch=res.get("pil_mismatch"),
                       done=res.get("pil_done") == 0xC0FFEE, overflow=res.get("pil_overflow"),
                       max_anchors=res.get("pil_max_anchors"), resets=res.get("pil_resets"),
                       stack_bytes=res.get("pil_stack_bytes"),
                       code_bytes=text - trace_bytes, gate_state_bytes=gate_bss,
                       ram_static_bytes=sec.get(".data", 0) + sec.get(".bss", 0),
                       ram_limit=b["ram"][1], flash_limit=b["flash"][1],
                       insn_median=float(np.median(per)) if len(per) else None,
                       insn_p99=float(np.quantile(per, 0.99)) if len(per) else None,
                       insn_max=float(per.max()) if len(per) else None)
            for cpi in (1, 2):
                if row["insn_median"]:
                    row[f"us_median_cpi{cpi}"] = row["insn_median"] * cpi / b["mhz"]
                    row[f"us_max_cpi{cpi}"] = row["insn_max"] * cpi / b["mhz"]
            out["boards"].setdefault(bk, {})[scen] = row
            print(f"  {bk:10s} done={row['done']} mism={row['mismatch']} ticks={row['ticks_executed']} "
                  f"insn med={row['insn_median']} max={row['insn_max']} stack={row['stack_bytes']} "
                  f"ram={row['ram_static_bytes']}/{b['ram'][1]} gate_state={gate_bss}", flush=True)
    json.dump(out, open(RES / "kic_pil.json", "w"), indent=1, default=float)


if __name__ == "__main__":
    main()
