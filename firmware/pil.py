"""Processor-in-the-loop (PIL) evaluation of the KIC gate on emulated IoT MCUs.

1. Run the Python closed loop (the reference) and record, per tick, what the
   gate saw (parsed proposal, measured exogenous drivers and cost) and what it
   produced (nominal and applied actions).
2. Replay that trace through the C port of the gate (firmware/src/kic_gate.c)
   compiled for each MCU and executed in the Renode instruction-set emulator.
   If every tick's decision matches, the closed loop with the firmware gate is
   identical to the reference loop.
3. Record executed instructions per tick (emulator hook), flash/RAM footprint
   (linker, against each part's REAL memory size), and stack high-water mark.

Latency at the part's clock is reported for 1 and 2 cycles per instruction,
bracketing Cortex-M/RISC-V in-order pipelines with flash wait states; these
are emulated instruction counts, not cycle-accurate or energy measurements.
"""
