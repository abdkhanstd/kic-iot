"""Processor-in-the-loop comparison: the gates KIC is compared against, on the
same emulated MCUs and with the same protocol as firmware/pil.py.

Each gate is run in its OWN Python closed loop (so its trace reflects its own
decisions), and that trace is replayed through the C port
(firmware/src/baselines.c) on every board, checking the decision tick by tick.
Gates:
  none          execute the proposal
  gstar_target  claim-free graph-sign rule (reference graph G*)
  gstar_claims  the published claim-driven verifier (parses the proposal text)
  obsadj        Obs.-sign: local-adjusted observational estimator, sign only
  obsci         Obs.-CI: the same with a one-sided bound (CIVeX-like)
  obsci_lite    Obs.-CI with every 10th logged row and a 100-tick live window
The observational gates carry their telemetry log in flash and their live
window in RAM; both are part of the gate's footprint. A gate that does not fit
the emulator's memory model cannot be run; one that runs in the model but
exceeds the real part's memory is reported as not deployable on that part.
"""
import argparse
import json
import os
import re
import subprocess
import sys

import numpy as np

from pil import BOARDS, BUILD, FW, RES, RENODE, sh

sys.path.insert(0, str(FW.parent / "src"))
sys.path.insert(0, str(FW.parent / "experiments"))

GATES = {"none": 0, "gstar_target": 1, "gstar_claims": 2, "obsadj": 3, "obsci": 3, "obsci_lite": 3}
STATELESS = {"none", "gstar_target", "gstar_claims"}
# emulator memory models (Renode .repl), used for linking; real limits are in BOARDS
MODEL = {"cc2538": (1024 * 1024, 256 * 1024), "nrf52840": (1024 * 1024, 256 * 1024),
         "stm32f072": (128 * 1024, 16 * 1024), "stm32f407": (2048 * 1024, 256 * 1024),
         "fe310": (512 * 1024 * 1024, 16 * 1024)}
QOS = ["latency", "throughput", "packet_loss", "energy"]
HCOLS = ["duty_cycle", "tx_power", "cost", "interference", "link_quality", "arrival_rate"]


def make_trace(scen, gate, seed, n_steps):
    from kic_attacks import build_world, scenario
    from certify.loop import RunConfig, run, subsample_hist, ACTUATORS
    from certify.oracle import cost_sign_from_graph, majority_path_sign
    W = make_trace.world = getattr(make_trace, "world", None) or build_world()
    prop, gstar, spoof, hist, exc = scenario(scen, seed, W)
    tr = []
    r0 = np.random.default_rng(seed + 99)
    nominal0 = [float(r0.uniform(0.1, 0.9)), float(r0.uniform(0.1, 0.9))]
    res = run(RunConfig(gate=gate, n_steps=n_steps, seed=seed, excitation=exc), prop, gstar=gstar,
              spoofer=spoof, surrogate=W["sur_clean"], hist=hist, pil_trace=tr)
    g, es = gstar
    T = dict(scenario=scen, gate=gate, seed=seed, nominal0=nominal0, trace=tr, ecost=res["ecost"],
             cost_sign=[cost_sign_from_graph(g, es, a) or 0 for a in ACTUATORS],
             implied=[[majority_path_sign(g, es, a, q) or 0 for q in QOS] for a in ACTUATORS])
    if gate in ("obsadj", "obsci", "obsci_lite"):
        H = subsample_hist(hist, 10) if gate == "obsci_lite" else hist
        T["hist"] = np.column_stack([H[k] for k in HCOLS])
        T["window"] = 100 if gate == "obsci_lite" else 2000
        T["z"] = 0.0 if gate == "obsadj" else 1.645
    return T


def c_str(s):
    out = []
    for ch in s.encode("utf-8"):
        c = chr(ch)
        out.append(c if 32 <= ch < 127 and c not in '"\\?' else f"\\{ch:03o}")
    return '"' + "".join(out) + '\\000"'


def write_header(T, lo, hi, path):
    tr = T["trace"]
    nom0 = T["nominal0"] if lo == 0 else tr[lo - 1]["nominal"]
    seg = tr[lo:hi]
    r = repr
    L = [f"/* generated by firmware/pil_baselines.py: {T['gate']} {T['scenario']} seed {T['seed']} "
         f"ticks {lo + 1}..{hi} */",
         f"#define TRACE_N {len(seg)}u", f"#define TRACE_T0 {lo + 1}u",
         f"static const double TRACE_NOMINAL0[2] = {{{r(float(nom0[0]))}, {r(float(nom0[1]))}}};",
         "static const signed char TRACE_PA[] = {" + ",".join(str(x["pa"]) for x in seg) + "};",
         "static const double TRACE_PV[] = {" + ",".join(r(x["pv"]) for x in seg) + "};",
         "static const double TRACE_NOM[][2] = {" + ",".join("{%r,%r}" % tuple(x["nominal"]) for x in seg) + "};",
         "static const int8_t GATE_COST_SIGN[2] = {%d,%d};" % tuple(T["cost_sign"]),
         "static const int8_t GATE_IMPLIED[2][4] = {" + ",".join(
             "{" + ",".join(str(v) for v in row) + "}" for row in T["implied"]) + "};"]
    if T["gate"] == "gstar_claims":
        offs, blob, o = [], [], 0
        for x in seg:
            offs.append(o); blob.append(c_str(x["text"])); o += len(x["text"].encode()) + 1
        L += ["static const uint32_t TRACE_TOFF[] = {" + ",".join(map(str, offs)) + "};",
              "static const char TRACE_TEXT[] = " + "\n".join(blob) + ";"]
    else:
        L += ["static const uint32_t TRACE_TOFF[1] = {0};", 'static const char TRACE_TEXT[] = "";']
    if "hist" in T:
        L += [f"#define HIST_N {len(T['hist'])}", f"#define OBS_WINDOW {T['window']}",
              f"#define OBS_Z {T['z']!r}",
              "static const double HIST[][6] = {" + ",".join(
                  "{" + ",".join(r(float(v)) for v in row) + "}" for row in T["hist"]) + "};",
              "static const double TRACE_EXO[][3] = {" + ",".join(
                  "{%r,%r,%r}" % tuple(x["exo"]) for x in seg) + "};",
              "static const double TRACE_COST[] = {" + ",".join(r(x["cost"]) for x in seg) + "};"]
    path.write_text("#include <stdint.h>\n" + "\n".join(L) + "\n")


HOST_DRV = r"""
#include <stdio.h>
#include <math.h>
#include "baselines.h"
#include "trace.h"
#if GATE_BASE == 3
static obs_gate_t O; static double LIVE[OBS_WINDOW][6];
#endif
int main(void){ double cur[2]={TRACE_NOMINAL0[0],TRACE_NOMINAL0[1]}, nxt[2]; unsigned i, mism=0, first=0;
#if GATE_BASE == 3
  obs_init(&O, HIST, HIST_N, LIVE, OBS_WINDOW, OBS_Z);
#endif
  for (i = 0; i < TRACE_N; i++) {
#if GATE_BASE == 0
    gate_none(TRACE_PA[i], TRACE_PV[i], cur, nxt);
#elif GATE_BASE == 1
    gate_gstar_target(TRACE_PA[i], TRACE_PV[i], cur, GATE_COST_SIGN, nxt);
#elif GATE_BASE == 2
    gate_gstar_claims(TRACE_TEXT + TRACE_TOFF[i], cur, GATE_IMPLIED, nxt);
#else
    obs_decide(&O, TRACE_PA[i], TRACE_PV[i], cur, nxt);
#endif
    if (fabs(nxt[0]-TRACE_NOM[i][0])>1e-9||fabs(nxt[1]-TRACE_NOM[i][1])>1e-9) {
      if (!mism) { first = i + 1; printf("first mismatch t=%u got %.9f %.9f want %.9f %.9f\n", first, nxt[0], nxt[1], TRACE_NOM[i][0], TRACE_NOM[i][1]); }
      mism++; nxt[0]=TRACE_NOM[i][0]; nxt[1]=TRACE_NOM[i][1]; }
#if GATE_BASE == 3
    obs_observe(&O, nxt, TRACE_EXO[i], TRACE_COST[i]);
#endif
    cur[0]=nxt[0]; cur[1]=nxt[1]; }
  printf("ticks %u mismatch %u first %u\n", TRACE_N, mism, first); return 0; }
"""


def build_host(T, hdr_dir):
    """Replay the whole trace on the host first: gate logic equivalence."""
    write_header(T, 0, len(T["trace"]), hdr_dir / "trace.h")
    exe, drv = hdr_dir / "pil_host_base", hdr_dir / "host_base.c"
    drv.write_text(HOST_DRV)
    sh(f"gcc -O2 -std=c99 -DGATE_BASE={GATES[T['gate']]} -I{hdr_dir} -I{FW/'src'} "
       f"{drv} {FW/'src/baselines.c'} -lm -o {exe}")
    return sh(str(exe))


def build_fw(bk, gate, hdr_dir, tag):
    b = BOARDS[bk]
    fl, ram = MODEL[bk]
    ld = BUILD / f"{bk}_{tag}_model.ld"
    ld.write_text((FW / "src/link.ld.in").read_text()
                  .replace("@FLASH_ORIGIN@", hex(b["flash"][0])).replace("@FLASH_LEN@", str(fl))
                  .replace("@RAM_ORIGIN@", hex(b["ram"][0])).replace("@RAM_LEN@", str(ram)))
    elf = BUILD / f"{bk}_{tag}.elf"
    start = FW / ("src/startup_cm.c" if b["arch"] == "cm" else "src/startup_rv.S")
    p = subprocess.run(
        f"{b['cc']}gcc {b['flags']} -O2 -ffunction-sections -fdata-sections -Wl,--gc-sections "
        f"-DGATE_BASE={GATES[gate]} -nostartfiles {'-Wl,-e,_start' if b['arch'] == 'rv' else ''} "
        f"-T {ld} -I{hdr_dir} -I{FW/'src'} {start} {FW/'src/main_pil.c'} {FW/'src/baselines.c'} "
        f"{FW/'src/kic_gate.c'} -lm -lc -lgcc -o {elf}", shell=True, capture_output=True, text=True)
    if p.returncode:
        return None, p.stderr
    size = sh(f"{b['cc']}size -A {elf}")
    sec = {m.group(1): int(m.group(2)) for m in re.finditer(r"^(\.\w+)\s+(\d+)", size, re.M)}
    syms, sizes = {}, {}
    for line in sh(f"{b['cc']}nm -S {elf}").splitlines():
        q = line.split()
        if len(q) == 4:
            sizes[q[3]] = int(q[1], 16); syms[q[3]] = int(q[0], 16)
        elif len(q) == 3:
            syms[q[2]] = int(q[0], 16)
    trace_bytes = sum(v for k, v in sizes.items() if k.startswith("TRACE_"))
    return dict(elf=elf, sec=sec, syms=syms, trace_bytes=trace_bytes,
                hist_bytes=sizes.get("HIST", 0), live_bytes=sizes.get("LIVE", 0)), None


def run_renode(bk, elf, syms, sim_seconds):
    b = BOARDS[bk]
    resc = elf.with_suffix(".resc")
    boot = (f"cpu VectorTableOffset {hex(b['flash'][0])}" if b["arch"] == "cm"
            else f"cpu PC {hex(syms['_start'])}")
    names = ["pil_mismatch", "pil_first_mismatch", "pil_ticks", "pil_stack_bytes", "pil_done"]
    reads = "\n".join(f"sysbus ReadDoubleWord {hex(syms[n])}" for n in names)
    # at pil_finish: log the result words and stop the emulator (no idle tail)
    fin = ("; ".join(f"self.Log(LogLevel.Warning, 'RES {n} %d' % machine.SystemBus.ReadDoubleWord({hex(syms[n])}))"
                     for n in names))
    rlog = elf.with_suffix(".rlog")
    rlog.unlink(missing_ok=True)
    # log to a file: the console log source crashes on the volume of
    # per-tick messages a long replay produces, ending the run early
    resc.write_text(f'''logFile @{rlog} true
logLevel 3 console
mach create "dut"
machine LoadPlatformDescription @{b["repl"]}
sysbus LoadELF @{elf}
{boot}
cpu AddHook {hex(syms["tick_done"] & ~1)} "self.Log(LogLevel.Warning, 'INSN %d' % self.ExecutedInstructions)"
cpu AddHook {hex(syms["pil_finish"] & ~1)} "{fin}"
emulation RunFor "{sim_seconds}"
{reads}
quit
''')
    # Renode's console input source spins on EOF and eventually dies mid-replay,
    # taking the emulation with it; hand it a pipe that never closes
    rfd, wfd = os.pipe()
    try:
        out = subprocess.run(f"./renode --disable-gui --console -e 'include @{resc}'", shell=True,
                             cwd=RENODE, stdin=rfd, capture_output=True, text=True,
                             timeout=36000).stdout
    finally:
        os.close(rfd); os.close(wfd)
    elf.with_suffix(".log").write_text(out)
    if rlog.exists():
        # the file log is the complete one; stdout carries the same lines and
        # would double-count them (and its log source dies on long replays)
        out = rlog.read_text() + "\n" + "\n".join(
            l for l in out.splitlines() if "INSN" not in l)
    insn = [int(x) for x in re.findall(r"INSN (\d+)", out)]
    res = {m.group(1): int(m.group(2)) for m in re.finditer(r"RES (\w+) (\d+)", out)}
    if not res:
        vals = re.findall(r"^(0x[0-9A-Fa-f]{8})\s*$", out, re.M)
        res = dict(zip(names, [int(v, 16) for v in vals[-len(names):]])) if len(vals) >= len(names) else {}
    return insn, res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--gates", nargs="*", default=list(GATES))
    ap.add_argument("--scenarios", nargs="*", default=["clean", "a1_telemetry", "spoof_blind"])
    ap.add_argument("--boards", nargs="*", default=list(BOARDS))
    ap.add_argument("--n_steps", type=int, default=800)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--sim_seconds", default=None,
                    help="emulated seconds per replay; default 1200 for the full observational "
                         "gates (they need ~1.5-3 s per tick), 60 otherwise")
    ap.add_argument("--out", default="kic_pil_baselines.json")
    args = ap.parse_args()
    BUILD.mkdir(exist_ok=True)
    outp = RES / args.out
    out = json.load(open(outp)) if outp.exists() else dict(boards={}, host={})
    for gate in args.gates:
        for scen in args.scenarios:
            T = make_trace(scen, gate, args.seed, args.n_steps)
            hdr = BUILD / f"hdr_{gate}_{scen}_{'_'.join(args.boards)}"
            hdr.mkdir(exist_ok=True)
            host = build_host(T, hdr).strip()
            print(f"[{gate}|{scen}] reference ecost {T['ecost']:.3f}; host: {host}", flush=True)
            out["host"][f"{gate}|{scen}"] = dict(host=host, ecost=T["ecost"])
            N = len(T["trace"])
            for bk in args.boards:
                b = BOARDS[bk]
                # stateless gates: split the replay trace (test harness only)
                # into several images if it does not fit the emulated flash
                chunks = [1, 2, 4, 8] if gate in STATELESS else [1]
                built, err = None, None
                for k in chunks:
                    bounds = [round(N * i / k) for i in range(k + 1)]
                    imgs = []
                    for c in range(k):
                        write_header(T, bounds[c], bounds[c + 1], hdr / "trace.h")
                        B, err = build_fw(bk, gate, hdr, f"{gate}_{scen}_{c}")
                        if B is None:
                            break
                        imgs.append(B)
                    if len(imgs) == k:
                        built = imgs
                        break
                row = dict(board=b["name"], core=b["core"], mhz=b["mhz"], gate=gate,
                           ram_limit=b["ram"][1], flash_limit=b["flash"][1])
                if built is None:
                    row.update(runs=False, fits=False,
                               error=re.findall(r"region `\w+' overflowed by \d+ bytes", err or "")[:2])
                    out["boards"].setdefault(bk, {})[f"{gate}|{scen}"] = row
                    print(f"  {bk:10s} does not fit the emulator memory model: {row['error']}", flush=True)
                    continue
                per, mism, done, stack = [], 0, True, 0
                for B in built:
                    # generous virtual time; the firmware idles after pil_done
                    secs = args.sim_seconds or ("1200" if gate in ("obsadj", "obsci") else "60")
                    insn, res = run_renode(bk, B["elf"], B["syms"], secs)
                    per += list(np.diff(np.array(insn, dtype=np.int64)))
                    mism += res.get("pil_mismatch", 10 ** 9)
                    done &= res.get("pil_done") == 0xC0FFEE
                    stack = max(stack, res.get("pil_stack_bytes", 0))
                B = built[0]
                sec = B["sec"]
                flash_need = sec.get(".text", 0) + sec.get(".data", 0) - B["trace_bytes"]
                ram_need = sec.get(".data", 0) + sec.get(".bss", 0) + stack
                per = np.array(per[1:] if len(built) == 1 else per, dtype=float)
                row.update(runs=True, images=len(built), done=done, mismatch=mism, ticks_executed=len(per),
                           stack_bytes=stack, flash_bytes=flash_need, hist_bytes=B["hist_bytes"],
                           live_bytes=B["live_bytes"], ram_static_bytes=sec.get(".data", 0) + sec.get(".bss", 0),
                           ram_bytes=ram_need,
                           fits=flash_need <= b["flash"][1] and ram_need <= b["ram"][1],
                           insn_median=float(np.median(per)) if len(per) else None,
                           insn_p99=float(np.quantile(per, 0.99)) if len(per) else None,
                           insn_max=float(per.max()) if len(per) else None)
                for cpi in (1, 2):
                    if row["insn_median"] is not None:
                        row[f"us_median_cpi{cpi}"] = row["insn_median"] * cpi / b["mhz"]
                        row[f"us_max_cpi{cpi}"] = row["insn_max"] * cpi / b["mhz"]
                out["boards"].setdefault(bk, {})[f"{gate}|{scen}"] = row
                print(f"  {bk:10s} imgs={len(built)} done={done} mism={mism} ticks={len(per)} "
                      f"insn med={row['insn_median']} max={row['insn_max']} flash={flash_need} "
                      f"ram={ram_need}/{b['ram'][1]} fits={row['fits']}", flush=True)
                json.dump(out, open(outp, "w"), indent=1, default=float)
    json.dump(out, open(outp, "w"), indent=1, default=float)


if __name__ == "__main__":
    main()
