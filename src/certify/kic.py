"""Keyed Interventional Certificates (KIC).

The verifier in verify.py judges a proposal against a reference graph G*.
Its authority is therefore only as good as G*, and G* is observational
knowledge: an attacker who controls the telemetry it was fitted from, the
sites it was fused across, or the corpus distilled from it can shape it.
KIC replaces that trust with *design-based* evidence that no upstream stage
can reach.

On every control tick the gate superimposes a small keyed dither on each
actuator,

    u_{t,j} = c_{t,j} + delta * s_{t,j},    s_{t,j} = PRF_K(t, j) in {-1,+1},

where c_t is the nominal (accepted or fallback) action and K is a key held
only by the gate. Because s_t is generated by the gate and is independent of
the plant, of every model, and of anything an attacker who lacks K can
inject, the plant response is a randomized experiment:

    E[ s_{t,j} (y_t - yhat_t) ] = E[ s_{t,j} y_t ]
                                = (m(c_j + delta) - m(c_j - delta)) / 2,

for ANY predictor yhat_t that is fixed before s_t is drawn. So:

  * the estimand is the plant's own local total effect of actuator j on y,
    not a sign read off a graph, and path cancellation cannot fool it;
  * every untrusted model (the distilled LM, a poisoned discovered graph, a
    fused federated graph) may serve as a control variate yhat: a good one
    shortens time-to-certificate, a poisoned one lengthens it, and neither
    can bias the certificate (Lemma 1 in the paper);
  * an attacker who spoofs telemetry without knowing K adds a term that is
    independent of s_t and therefore mean-zero in the estimator, while the
    same spoof can forge ANY observational relation (Corollary 1).

The increments are bounded, so an anytime-valid empirical-Bernstein
confidence sequence (Waudby-Smith & Ramdas, JRSS-B 2024, predictable plug-in
EB) gives a certificate whose false-certification probability is at most
alpha uniformly over time, however the proposals were chosen.
"""
from __future__ import annotations

import dataclasses
import hashlib
import hmac
import math
from typing import Callable, Optional

import numpy as np


# ---------------------------------------------------------------------------
# keyed excitation
# ---------------------------------------------------------------------------

class KeyedRademacher:
    """s_{t,j} = +-1 from HMAC-SHA256(K, t || j). Unpredictable without K."""

    def __init__(self, key: bytes):
        self.key = key

    def sign(self, t: int, j: int) -> int:
        d = hmac.new(self.key, f"{t}:{j}".encode(), hashlib.sha256).digest()
        return 1 if d[0] & 1 else -1


class PublicSinusoid:
    """Ablation: a deterministic, public dither (as in extremum-seeking
    control). Predictable by anyone, so a telemetry spoofer can correlate
    with it. Returned as a sign to keep the estimator identical."""

    def __init__(self, periods=(4, 6)):
        self.periods = periods

    def sign(self, t: int, j: int) -> int:
        return 1 if math.sin(2 * math.pi * (t + 0.5) / self.periods[j % len(self.periods)]) >= 0 else -1


# ---------------------------------------------------------------------------
# anytime-valid confidence sequence for the mean of a [0,1]-bounded process
# ---------------------------------------------------------------------------

class EBConfSeq:
    """Predictable plug-in empirical-Bernstein CS (Waudby-Smith & Ramdas).

    For X_t in [0,1] with conditional means mu_t = E[X_t | past], the process
    prod_i exp(lam_i (X_i - mu_i) - v_i psi_E(lam_i)) is a nonnegative
    supermartingale for predictable lam_i (Howard et al. 2021; Waudby-Smith &
    Ramdas 2024), so with probability >= 1 - alpha, simultaneously for all t,
        sum_i lam_i mu_i / sum_i lam_i  lies in  [lo_t, hi_t].
    That is the estimand when the nominal action (hence mu_t) moves.
    """

    CAP = 0.75

    def __init__(self, alpha: float, c: Optional[float] = None):
        self.alpha = alpha
        self.c = c if c is not None else EBConfSeq.CAP
        self.t = 0
        self.sum_x = 0.0
        self.sum_sq = 0.0          # sum (x_i - mu_hat_{i-1})^2 for sigma_hat
        self.mu_hat = 0.5
        self.sig2_hat = 0.25
        self.sum_lam = 0.0
        self.sum_lam_x = 0.0
        self.sum_v_psi = 0.0
        self.lo, self.hi = 0.0, 1.0
        self._log = math.log(2.0 / alpha)
        self.last_lam = 0.0
        # lambda-weighted moments of when and where the evidence was taken
        # (Theorem 3 converts the certified weighted average into a bound on
        # the CURRENT slope at the CURRENT action from these)
        self.sum_lam_tau = 0.0
        self.sum_lam_c = None
        self.sum_lam_c2 = 0.0
        self.near = None           # companion upper CS on the near-clip frequency

    @staticmethod
    def _psi(lam: float) -> float:
        return (-math.log(1.0 - lam) - lam) / 4.0

    def next_lam(self) -> float:
        t = self.t + 1
        return min(math.sqrt(2.0 * self._log / (self.sig2_hat * t * math.log(1.0 + t))), self.c)

    def update(self, x: float, tau: Optional[int] = None, loc: Optional[np.ndarray] = None,
               near: Optional[int] = None) -> None:
        x = min(max(x, 0.0), 1.0)
        lam = self.next_lam()
        self.t += 1
        t = self.t
        self.last_lam = lam
        if tau is not None:
            self.sum_lam_tau += lam * tau
        if loc is not None:
            # moments about the first location, so rms_dist does not cancel
            if self.sum_lam_c is None:
                self.loc0 = np.array(loc, dtype=float)
                self.sum_lam_c = np.zeros_like(self.loc0)
            z = loc - self.loc0
            self.sum_lam_c = self.sum_lam_c + lam * z
            self.sum_lam_c2 += lam * float(z[0] * z[0] + z[1] * z[1]) if len(z) == 2 else lam * float(z @ z)
        if near is not None and self.near is not None:
            self.near.update(near, lam)
        v = 4.0 * (x - self.mu_hat) ** 2
        self.sum_lam += lam
        self.sum_lam_x += lam * x
        self.sum_v_psi += v * self._psi(lam)
        # predictable estimates for the NEXT step
        self.sum_x += x
        self.sum_sq += (x - self.mu_hat) ** 2
        self.mu_hat = (0.5 + self.sum_x) / (t + 1)
        self.sig2_hat = (0.25 + self.sum_sq) / (t + 1)
        centre = self.sum_lam_x / self.sum_lam
        width = (self._log + self.sum_v_psi) / self.sum_lam
        # No running intersection: the target is the lambda-weighted average
        # of time-varying conditional means, which moves as the nominal action
        # moves, and intersecting intervals is only valid for a fixed target.
        # The un-intersected sequence is still valid uniformly over time.
        self.lo = max(0.0, centre - width)
        self.hi = min(1.0, centre + width)

    def interval(self) -> tuple[float, float]:
        return self.lo, self.hi

    def mean_age(self, now: int) -> float:
        """lambda-weighted age of the evidence, sum lam_i (now - tau_i) / sum lam_i."""
        return now - self.sum_lam_tau / self.sum_lam if self.sum_lam else 0.0

    def rms_dist(self, x: np.ndarray) -> float:
        """lambda-weighted RMS distance from x to the actions the evidence covers
        (an upper bound on the weighted mean distance, by Jensen)."""
        if not self.sum_lam or self.sum_lam_c is None:
            return 0.0
        z = x - self.loc0
        zs = sum(float(z[k]) * float(self.sum_lam_c[k]) for k in range(len(z)))
        zz = sum(float(z[k]) * float(z[k]) for k in range(len(z)))
        m2 = (self.sum_lam_c2 - 2.0 * zs + zz * self.sum_lam) / self.sum_lam
        return math.sqrt(max(m2, 0.0))


def alpha_share(k: int, spend: str = "basel") -> float:
    """Share of alpha given to the k-th certificate (k >= 1); sums to 1 over k."""
    if spend == "basel":
        return 6.0 / (math.pi ** 2 * k ** 2)
    if spend.startswith("flat:"):
        k0 = float(spend.split(":")[1])
        return (k0 + 1.0) / ((k + k0) * (k + k0 + 1.0))
    raise ValueError(spend)


class UpperMeanCS:
    """One-sided empirical-Bernstein upper confidence sequence for the
    lambda-weighted mean of a {0,1} (or [0,1]) process, run with EXTERNALLY
    supplied predictable weights lambda_i -- the main certificate's -- so that
    it bounds the same weighted average the certificate targets. Applying the
    EB supermartingale to 1 - Z_i gives, uniformly in t with prob >= 1 - alpha,
        sum lam_i pi_i / sum lam_i <= (sum lam_i Z_i + log(1/alpha) + sum v_i psi(lam_i)) / sum lam_i.
    """

    def __init__(self, alpha: float):
        self._log = math.log(1.0 / alpha)
        self.n = 0
        self.sum_z = 0.0
        self.mu_hat = 0.0
        self.sum_lam = self.sum_lam_z = self.sum_v_psi = 0.0

    def update(self, z: float, lam: float) -> None:
        v = 4.0 * (z - self.mu_hat) ** 2
        self.sum_lam += lam
        self.sum_lam_z += lam * z
        self.sum_v_psi += v * EBConfSeq._psi(lam)
        self.n += 1
        self.sum_z += z
        self.mu_hat = (0.5 + self.sum_z) / (self.n + 1) if self.n else 0.0

    def upper(self) -> float:
        if not self.sum_lam:
            return 1.0
        return min(1.0, (self.sum_lam_z + self._log + self.sum_v_psi) / self.sum_lam)


# ---------------------------------------------------------------------------
# certificate bank: one CS per (actuator, target, operating cell)
# ---------------------------------------------------------------------------

@dataclasses.dataclass
class Certificate:
    sign: int              # +1 / -1 certified sign of d target / d actuator, 0 = uncertified
    lo: float              # CS on the local effect, in target units per unit actuator
    hi: float
    n: int
    extent: float = 0.0    # max L-inf distance from the query point to any visit it covers
    clip_frac: float = 0.0 # share of this certificate's updates in which clipping was active
    suspended: bool = False
    # Theorem 3 terms (robust mode): clipping bias bound G*U, weighted RMS
    # distance of the evidence from the query action, weighted age in ticks
    bias: float = 0.0
    eta: float = 0.0
    age: float = 0.0
    robust: bool = False


class CertificateBank:
    def __init__(self, actuators: list[str], targets: list[str], delta: float,
                 alpha: float = 0.05, grid: int = 4, bounds: Optional[dict] = None,
                 window: Optional[int] = 150, anchor_radius: Optional[float] = None,
                 family_wise: bool = False, decision_targets: Optional[list] = None,
                 clip_guard: Optional[float] = 0.01, robust: bool = False,
                 G: float = 2.0, V: float = 0.0, L: float = 3.0, near_share: float = 0.2,
                 spend: str = "basel", leak: float = 0.0, leak_F: Optional[float] = None,
                 w_extra: float = 0.0, bound_control_variate: bool = False):
        self.actuators = actuators
        self.targets = targets
        self.delta = delta
        self.alpha = alpha
        self.grid = grid
        self.bounds = bounds or {}        # |y - yhat| bound per target (default 1)
        self._cs: dict = {}
        self._shadow: dict = {}           # next window's CS, started once the current one is full
        self.window = window              # certificates cover at most the last 2*window visits
        # anchor_radius=None: fixed grid cells. Otherwise certificates are
        # anchored at the operating point where their evidence started and
        # cover only actions within this L-inf radius of it; the anchor for a
        # tick is a function of the past and the current centre only, so the
        # assignment is predictable and validity is unaffected.
        self.anchor_radius = anchor_radius
        self._anchors: list = []
        self._cell_mean: dict = {}        # predictable fallback control variate
        self._sw: dict = {}               # running sum s*r per key, for beta_hat
        self.n_clip = 0
        self.n_obs = 0
        # Deployment-level error control. With family_wise=True the k-th
        # certificate created for a decision target (over all anchors,
        # windows and resets) runs at alpha_k = alpha * 6 / (pi^2 k^2), so
        # the probability that ANY certificate the gate can act on is ever
        # wrong is at most sum_k alpha_k = alpha.
        # spend='basel': alpha_k = 6 alpha / (pi^2 k^2);
        # spend='flat:k0': alpha_k = alpha (k0+1) / ((k+k0)(k+k0+1)), which also
        # sums to alpha but spends less on the first certificates and more on
        # later ones (the telescoping series 1/(k+k0) - 1/(k+k0+1)).
        self.family_wise = family_wise
        self.spend = spend
        self.decision_targets = set(decision_targets) if decision_targets else set(targets)
        self.k_created = 0
        # A certificate whose updates were clipped more often than clip_guard
        # is suspended (treated as uncertified): Theorem 2 certifies the
        # clipped estimand, which equals the local effect only when clipping
        # is inactive.
        self.clip_guard = clip_guard
        # Robust mode (Theorem 3). The certificate is widened by
        #   G * U_t      bias of clipping: |D| <= delta*G per realization, so
        #                clipping can act (in either arm) only on ticks with
        #                |r| > B - 2 delta G, whose weighted frequency U_t is
        #                upper-bounded by a companion CS at alpha*near_share
        #   L*(eta + delta/2) + V*(age + 1)
        #                from the certified weighted average to the slope of
        #                the CURRENT response at the CURRENT action
        # The 1% clip guard is then unnecessary and switched off.
        self.robust, self.G, self.V, self.L = robust, G, V, L
        self.near_share = near_share
        # Proposition 4 (leakage budget): if the attacker's side channel
        # distinguishes s_{t,j}=+1 from -1 with total-variation advantage at
        # most `leak` (eta), and the part of the cost forgery that depends on
        # it spans at most 2F (leak_F; None: unbounded, clipped at B), the
        # clipped response moves by at most min(F, B) * eta per tick, so the
        # interval is widened by min(F, B) * eta / delta in slope units. The
        # near-clip companion stays valid: it is computed from observed ticks.
        self.leak = leak
        self.leak_F = leak_F
        # certified envelopes that hold outside a noise-tail event of per-tick
        # probability eps add Gbar * eps to the width (supplement, Sec. S3)
        self.w_extra = w_extra
        # Optional numerical/variance stabilization for large actuator counts.
        # Only PAST estimates of OTHER coordinates are clipped, so the term
        # remains independent of the current coordinate's secret sign. It
        # does not shrink the confidence interval or assume a trusted predictor.
        # Opt-in preserves all archived experimental configurations.
        self.bound_control_variate = bound_control_variate
        self.tick = 0
        if robust:
            self.clip_guard = None

    def _new_cs(self, target: str) -> "EBConfSeq":
        a = self.alpha
        if self.family_wise and target in self.decision_targets:
            self.k_created += 1
            a = self.alpha * alpha_share(self.k_created, self.spend)
        if self.robust:
            cs = EBConfSeq(a * (1.0 - self.near_share))
            cs.near = UpperMeanCS(a * self.near_share)
        else:
            cs = EBConfSeq(a)
        cs.nclip = 0
        cs.box_lo = cs.box_hi = None
        return cs

    def reset(self) -> None:
        self._cs, self._shadow, self._cell_mean, self._sw = {}, {}, {}, {}
        self._anchors = []
        self.n_resets = getattr(self, "n_resets", 0) + 1

    def cell(self, centre: dict, create: bool = False) -> tuple:
        if self.anchor_radius is None:
            return tuple(min(int(centre[a] * self.grid), self.grid - 1) for a in self.actuators)
        x = np.array([centre[a] for a in self.actuators])
        best, bd = None, None
        for i, an in enumerate(self._anchors):
            d = float(np.max(np.abs(an - x)))
            if d <= self.anchor_radius + 1e-12 and (bd is None or d < bd):
                best, bd = i, d
        if best is None:
            if not create:
                return ("new",)
            self._anchors.append(x)
            best = len(self._anchors) - 1
        return ("anchor", best)

    def _get(self, key):
        if key not in self._cs:
            self._cs[key] = self._new_cs(key[1])
        return self._cs[key]

    @staticmethod
    def _visit(cs, x: np.ndarray, clipped: bool) -> None:
        cs.nclip += int(clipped)
        cs.box_lo = x.copy() if cs.box_lo is None else np.minimum(cs.box_lo, x)
        cs.box_hi = x.copy() if cs.box_hi is None else np.maximum(cs.box_hi, x)

    def baseline(self, target: str, cell: tuple) -> float:
        """Running mean of y in this cell -- measurable before s_t is drawn."""
        m = self._cell_mean.get((target, cell))
        return m[0] / m[1] if m and m[1] else 0.5

    def update(self, centre: dict, signs: dict, y: dict, yhat: Optional[dict] = None) -> None:
        """One dithered tick. For actuator j the residual also removes the
        other actuators' dither contribution delta*s_i*beta_i using effect
        estimates from PAST ticks only; s_i is independent of s_j, so this
        term is mean-zero against s_j and removing it cannot bias the j
        certificate, it only removes variance."""
        cell = self.cell(centre, create=True)
        self.tick += 1
        for k in self.targets:
            base = yhat[k] if (yhat is not None and k in yhat) else self.baseline(k, cell)
            B = self.bounds.get(k, 1.0)
            r0 = y[k] - base
            # effect estimates from PAST ticks only, frozen before any of this
            # tick's updates (otherwise actuator b's estimate would already
            # contain s_b * r_t, which depends on s_a)
            bh = {b: self._beta_hat(b, k, cell) for b in self.actuators}
            for a in self.actuators:
                other = sum(self.delta * signs[b] * bh[b] for b in self.actuators if b != a)
                r = r0 - other
                clipped = abs(r) > B
                self.n_clip += int(clipped)
                self.n_obs += 1
                xc = np.array([centre[b] for b in self.actuators])
                w = signs[a] * float(np.clip(r, -B, B)) / B   # in [-1,1], mean ~ delta*beta/B
                key = (a, k, cell)
                x = (w + 1.0) / 2.0
                main = self._get(key)
                near = int(abs(r) > B - 2.0 * self.delta * self.G) if self.robust else None
                upd = dict(tau=self.tick, loc=xc, near=near)
                main.update(x, **upd)
                self._visit(main, xc, clipped)
                if self.window:
                    # Windowed certificates. The EB weights front-load early
                    # observations, so a never-restarted CS stays anchored to
                    # the first visits of a cell after the plant has moved or
                    # drifted. A shadow CS starts once the current one holds
                    # `window` observations and replaces it after another
                    # `window`; each window is a fresh, valid CS.
                    if main.t >= self.window:
                        if key not in self._shadow:
                            self._shadow[key] = self._new_cs(k)
                        sh = self._shadow[key]
                        sh.update(x, **upd)
                        self._visit(sh, xc, clipped)
                        if sh.t >= self.window:
                            self._cs[key] = sh
                            del self._shadow[key]
                            self.n_windows = getattr(self, "n_windows", 0) + 1
                sw, n = self._sw.get((a, k, cell), (0.0, 0))
                self._sw[(a, k, cell)] = (sw + signs[a] * r, n + 1)
            s_, c_ = self._cell_mean.get((k, cell), (0.0, 0))
            self._cell_mean[(k, cell)] = (s_ + y[k], c_ + 1)

    def _beta_hat(self, a, k, cell) -> float:
        sw, n = self._sw.get((a, k, cell), (0.0, 0))
        estimate = sw / (n * self.delta) if n else 0.0
        if self.bound_control_variate:
            return min(self.G, max(-self.G, estimate))
        return estimate

    def leak_width(self, target: str) -> float:
        if not self.leak:
            return 0.0
        B = self.bounds.get(target, 1.0)
        F = B if self.leak_F is None else min(self.leak_F, B)
        return self.leak * F / self.delta

    def current_slope_intervals(self, actuator: str, target: str, centre: dict) -> list:
        """Theorem-3 intervals [l - w(c), h + w(c)] on the current slope at the
        query action c, from EVERY live certificate (all anchors, main and
        shadow windows) of this actuator and target. On the event that all of
        them cover, they contain the same number, so they must intersect;
        an empty intersection therefore certifies that a declared envelope
        is violated, at no additional error probability (Proposition 5)."""
        out = []
        x = np.array([centre[b] for b in self.actuators])
        B = self.bounds.get(target, 1.0)
        for store in (self._cs, self._shadow):
            for (a, k, cell), cs in store.items():
                if a != actuator or k != target or cs.t == 0 or cs.near is None:
                    continue
                lo = (2 * cs.lo - 1) * B / self.delta
                hi = (2 * cs.hi - 1) * B / self.delta
                w = (self.G * cs.near.upper() + self.L * (cs.rms_dist(x) + 0.5 * self.delta)
                     + self.V * (cs.mean_age(self.tick) + 1) + self.leak_width(target) + self.w_extra)
                out.append((lo - w, hi + w, cell, store is self._shadow))
        return out

    def query(self, actuator: str, target: str, centre: dict) -> Certificate:
        key = (actuator, target, self.cell(centre))
        cs = self._cs.get(key)
        if cs is None:
            return Certificate(0, -math.inf, math.inf, 0)
        B = self.bounds.get(target, 1.0)
        lo = (2 * cs.lo - 1) * B / self.delta
        hi = (2 * cs.hi - 1) * B / self.delta
        sign = 1 if lo > 0 else (-1 if hi < 0 else 0)
        x = np.array([centre[b] for b in self.actuators])
        extent = 0.0
        if cs.box_lo is not None:
            extent = float(np.max(np.maximum(np.abs(x - cs.box_lo), np.abs(x - cs.box_hi))))
        clip_frac = cs.nclip / cs.t if cs.t else 0.0
        suspended = (self.clip_guard is not None and cs.nclip > max(1.0, self.clip_guard * cs.t))
        if suspended:
            sign = 0
        if self.robust:
            bias = (self.G * cs.near.upper() if cs.near is not None else 0.0) + self.leak_width(target) + self.w_extra
            return Certificate(sign, lo, hi, cs.t, extent, clip_frac, suspended,
                               bias=bias, eta=cs.rms_dist(x), age=cs.mean_age(self.tick), robust=True)
        return Certificate(sign, lo, hi, cs.t, extent, clip_frac, suspended)


class OnlineCV:
    """Predictable control variate needing no trusted model: a ridge
    regression of each target on the measured exogenous drivers (with
    squares and cross terms) and the nominal centre, refitted from PAST ticks
    only. The current exogenous reading may be used because exogenous
    drivers are not caused by the dither, so E[s_t g(exo_t, c_t)] = 0 for
    any g. It must never see the applied action or an endogenous variable.
    """

    def __init__(self, targets: list[str], exo: list[str], actuators: list[str],
                 ridge: float = 1e-3, warmup: int = 20, refit_every: int = 10):
        self.targets, self.exo, self.actuators = targets, exo, actuators
        self.ridge, self.warmup, self.refit_every = ridge, warmup, refit_every
        self.X, self.Y = [], {k: [] for k in targets}
        self.coef = None

    def _feat(self, obs: dict, centre: dict) -> np.ndarray:
        e = [obs[k] for k in self.exo]
        f = list(e) + [a * a for a in e]
        f += [e[i] * e[j] for i in range(len(e)) for j in range(i + 1, len(e))]
        f += [centre[a] for a in self.actuators] + [1.0]
        return np.array(f)

    def predict(self, obs: dict, centre: dict) -> Optional[dict]:
        if self.coef is None:
            return None
        x = self._feat(obs, centre)
        return {k: float(x @ self.coef[k]) for k in self.targets}

    def reset(self) -> None:
        self.X, self.Y, self.coef = [], {k: [] for k in self.targets}, None

    def update(self, obs: dict, centre: dict, y: dict) -> None:
        self.X.append(self._feat(obs, centre))
        for k in self.targets:
            self.Y[k].append(y[k])
        n = len(self.X)
        if n >= self.warmup and n % self.refit_every == 0:
            X = np.array(self.X[-3000:])
            A = X.T @ X + self.ridge * np.eye(X.shape[1])
            self.coef = {k: np.linalg.solve(A, X.T @ np.array(self.Y[k][-3000:]))
                         for k in self.targets}


class ExoChangeDetector:
    """Resets certificates when the measured exogenous drivers shift (a new
    regime can reverse a local effect, and a CS pooled across regimes would
    certify a stale average). Two-window z-test on each driver. A spoofer can
    trigger spurious resets -- a denial of certification that makes the gate
    MORE conservative -- but cannot forge a certificate this way."""

    def __init__(self, exo: list[str], recent: int = 25, min_base: int = 40, z: float = 5.0):
        self.exo, self.recent, self.min_base, self.z = exo, recent, min_base, z
        self.buf = []

    def update(self, obs: dict) -> bool:
        self.buf.append([obs[k] for k in self.exo])
        n = len(self.buf)
        if n < self.min_base + self.recent:
            return False
        A = np.array(self.buf)
        base, rec = A[:-self.recent], A[-self.recent:]
        sd = base.std(0) + 1e-6
        zz = np.abs(rec.mean(0) - base.mean(0)) / (sd / math.sqrt(self.recent))
        if zz.max() > self.z:
            self.buf = self.buf[-self.recent:]
            return True
        return False


