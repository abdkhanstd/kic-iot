class SwitchbackTrial:
    """Randomised A/B trial of a proposed move c -> c'. On each tick a keyed
    coin s_t picks the arm (c' if +1, c if -1), so

        E[ s_t (y_t - yhat_t) ] = (m(c') - m(c)) / 2

    for any yhat_t fixed before s_t (the control variate must be evaluated at
    the BASE action c, never at the arm). The CS is the same anytime-valid EB
    sequence. The trial ends at the first tick its CS excludes 0, or after
    `budget` ticks (abstain). Because the CS shrinks like
    sigma*sqrt(log(1/alpha)/n), a harmful step of size Delta is rejected
    after O(sigma^2 log(1/alpha) / Delta^2) ticks and its expected exposure
    Delta*n/2 is O(sigma^2 log(1/alpha) / Delta): the larger the harm, the
    shorter the exposure."""

    def __init__(self, base: dict, arm: dict, key: bytes, alpha: float, bound: float,
                 budget: int, t0: int, G: Optional[float] = None, V: float = 0.0,
                 near_share: float = 0.2):
        self.base, self.arm = dict(base), dict(arm)
        self.exc = KeyedRademacher(key + b"|trial|" + str(t0).encode())
        self.step = max(abs(arm[a] - base[a]) for a in base)
        # Robust (Proposition S2): per-realization half-contrast |D| <= G*step/2,
        # so clipping can act only when |r| > B - G*step; the certificate is
        # widened by the bias bound and by V*step*(weighted age + 1).
        self.G, self.V = G, V
        if G is not None:
            self.cs = EBConfSeq(alpha * (1.0 - near_share))
            self.cs.near = UpperMeanCS(alpha * near_share)
            bound = max(bound, G * self.step + 0.15)
        else:
            self.cs = EBConfSeq(alpha)
        self.B, self.budget, self.t0 = bound, budget, t0
        self.n = 0
        self.s = None

    def arm_for(self, t: int) -> dict:
        self.s = self.exc.sign(t, 0)
        return dict(self.arm if self.s > 0 else self.base)

    def update(self, y: float, yhat: float) -> None:
        r0 = y - yhat
        r = float(np.clip(r0, -self.B, self.B))
        near = int(abs(r0) > self.B - self.G * self.step) if self.G is not None else None
        self.cs.update((self.s * r / self.B + 1.0) / 2.0, tau=self.n + 1, near=near)
        self.n += 1

    def effect_ci(self) -> tuple[float, float]:
        """CI on m(c') - m(c), widened in robust mode (Proposition S2)."""
        lo, hi = self.cs.interval()
        lo, hi = (2 * lo - 1) * self.B * 2, (2 * hi - 1) * self.B * 2
        if self.G is not None:
            w = 2 * (0.5 * self.G * self.step * self.cs.near.upper()) \
                + self.V * self.step * (self.cs.mean_age(self.n) + 1)
            lo, hi = lo - w, hi + w
        return lo, hi

    def status(self) -> str:
        lo, hi = self.effect_ci()
        if hi < 0:
            return "BENEFICIAL"      # m(c') < m(c): cost goes down
        if lo > 0:
            return "HARMFUL"
        return "TIMEOUT" if self.n >= self.budget else "RUNNING"
