LO, HI = 0.02, 0.98


def dither(nominal: dict, t: int, excitation, delta: float, actuators: list[str]):
    """Centre each actuator at least delta inside its range so the +-delta
    excitation is always symmetric (a saturated actuator would otherwise make
    the design one-sided and the estimator biased)."""
    centre, signs, applied = {}, {}, {}
    for j, a in enumerate(actuators):
        c = float(np.clip(nominal[a], LO + delta, HI - delta))
        s = excitation.sign(t, j)
        centre[a], signs[a] = c, s
        applied[a] = c + delta * s
    return centre, signs, applied


@dataclasses.dataclass
class GateDecision:
    verdict: str           # ACCEPT | REJECT | HOLD
    reason: str
    action: dict           # nominal action to execute next (before dithering)
    certificate: Optional[Certificate] = None


class KICGate:
    """Accept a proposed move only if the plant itself has certified that
    moving that actuator in that direction improves the verifier-chosen
    objective. The objective is set by the gate, never read from the
    proposer's text, so omitting or fabricating a claimed effect changes
    nothing.

    A certified move is executed with its step capped at `cert_cap` (the
    certificate is local, so large steps are not covered by it).

    When a proposal is not accepted, the gate falls back to its own
    *certified reversionary controller*: a step of size `fallback_step`
    along the certified descent direction of whichever actuator has a
    certificate in the current cell, or HOLD if none does. This is the
    Simplex/RTA pattern with a reversionary controller whose every move is
    itself certified, instead of re-executing the last accepted action.

    modes for an UNCERTIFIED proposal:
      'hold'     never execute it (only certified moves ever run)
      'prior'    use a reference-graph sign (G*), if one is given
      'cautious' execute it with the step capped at `cautious_step`
      'trust'    earned-trust budget: an uncertified proposal may move the
                 plant by `cautious_step`, drawn from a budget of total
                 displacement `trust_radius`. The budget is refilled only
                 when a later certificate CONFIRMS a direction the proposer
                 took uncertified, and is revoked when one CONTRADICTS it.
                 A proposer that is right keeps earning freedom; one that is
                 wrong spends at most `trust_radius` of harm and is then
                 held to certified moves only.
    """

    def __init__(self, bank: CertificateBank, max_step: float = 0.35,
                 mode: str = "hold", cautious_step: float = 0.05,
                 prior_sign: Optional[Callable[[str, str], Optional[int]]] = None,
                 cert_cap: float = 0.1, fallback_step: float = 0.05, fallback: bool = True,
                 trust_radius: float = 0.15, L_hat: Optional[float] = None):
        self.bank = bank
        self.max_step = max_step
        self.mode = mode
        self.cautious_step = cautious_step
        self.prior_sign = prior_sign
        self.cert_cap = cert_cap
        self.fallback_step = fallback_step
        self.fallback = fallback
        self.trust_radius = trust_radius
        self.budget = trust_radius
        self.pending = []           # (actuator, direction, objective) taken uncertified
        self.n_confirm = self.n_revoke = 0
        # Declared smoothness bound |d^2 E J / da^2| <= L_hat. When set, a
        # certificate licenses only the step size Proposition 2 proves to
        # lower expected cost; None keeps the sign-only rule.
        self.L_hat = L_hat

    def certified_step(self, cert: Certificate, d: int, sense: int, cap: float) -> float:
        """Largest step in direction d that the certificate PROVES lowers E J.
        margin m: the confidence bound on d*beta closest to zero (in the
        improving direction); the current slope can differ from the
        certified average by at most L_hat*(extent + delta/2)."""
        if cert.sign == 0 or d * cert.sign != sense:
            return 0.0
        if self.L_hat is None:
            return cap
        m = -cert.hi if d > 0 else cert.lo          # for sense=-1 (minimise)
        if sense > 0:
            m = cert.lo if d > 0 else -cert.hi
        # |symmetric finite difference - slope| <= L*delta/2 at each visit,
        # and the slope moves by at most L*extent between a visit and here.
        if cert.robust:
            # Theorem 3: bound on the CURRENT slope at the
            # CURRENT action, accounting for clipping, locality and drift
            slack = (m - cert.bias - self.L_hat * (cert.eta + 0.5 * self.bank.delta)
                     - self.bank.V * (cert.age + 1))
        else:
            slack = m - self.L_hat * (cert.extent + 0.5 * self.bank.delta)
        if slack <= 0:
            return 0.0
        return float(min(cap, 2.0 * slack / self.L_hat))

    def _audit(self, current: dict, objective: str, sense: int) -> None:
        """Settle pending uncertified moves against certificates now available."""
        keep = []
        for (a, d, obj) in self.pending:
            c = self.bank.query(a, obj, current)
            if c.sign == 0:
                keep.append((a, d, obj))
            elif d * c.sign == sense:
                self.budget = self.trust_radius; self.n_confirm += 1
            else:
                self.budget = 0.0; self.n_revoke += 1
                keep = []
                break
        self.pending = keep[-8:]

    def reset_trust(self) -> None:
        self.budget, self.pending = self.trust_radius, []

    def _fallback(self, current: dict, objective: str, sense: int, reason: str,
                  cert=None) -> GateDecision:
        if self.fallback:
            best = None
            for a in self.bank.actuators:
                c = self.bank.query(a, objective, current)
                if c.sign == 0:
                    continue
                strength = min(abs(c.lo), abs(c.hi))
                d = sense * c.sign                     # direction that improves the objective
                st = self.certified_step(c, d, sense, self.fallback_step)
                if st <= 0:
                    continue
                v = float(np.clip(current[a] + d * st, LO, HI))
                if abs(v - current[a]) < 1e-9:
                    continue
                if best is None or strength > best[0]:
                    best = (strength, a, v, c)
            if best is not None:
                _, a, v, c = best
                nxt = dict(current); nxt[a] = v
                return GateDecision("FALLBACK", reason + "+CERTIFIED_FALLBACK", nxt, cert or c)
        return GateDecision("HOLD" if reason in ("NO_OP", "UNCERTIFIED") else "REJECT",
                            reason, dict(current), cert)

    def decide(self, proposal: Optional[dict], current: dict, objective: str,
               sense: int = -1) -> GateDecision:
        """proposal: {actuator: value} or None (unparseable). sense=-1 means
        the objective is to be minimised."""
        if not proposal:
            return self._fallback(current, objective, sense, "UNPARSEABLE")
        if self.mode == "trust":
            self._audit(current, objective, sense)
        (a, v), = proposal.items()
        if a not in self.bank.actuators:
            return self._fallback(current, objective, sense, "NON_ACTIONABLE")
        if not (0.0 <= v <= 1.0):
            return self._fallback(current, objective, sense, "OUT_OF_RANGE")
        step = float(np.clip(v - current[a], -self.max_step, self.max_step))
        if abs(step) < 1e-9 or abs(float(np.clip(current[a] + step, LO, HI)) - current[a]) < 1e-9:
            return self._fallback(current, objective, sense, "NO_OP")
        d = 1 if step > 0 else -1
        cert = self.bank.query(a, objective, current)
        # the move helps iff d * beta has the objective's sense
        if cert.sign != 0:
            if d * cert.sign == sense:
                cap = self.certified_step(cert, d, sense, self.cert_cap)
                if cap > 0:
                    st = float(np.clip(step, -cap, cap))
                    nxt = dict(current); nxt[a] = float(np.clip(current[a] + st, LO, HI))
                    return GateDecision("ACCEPT", "CERTIFIED_BENEFICIAL", nxt, cert)
                # The sign is certified but no step size is provably improving
                # (we are within L_hat*(extent+delta) of a stationary point).
                # Taking an uncertified step here would bypass Prop. 2, so the
                # gate holds or falls back instead of spending trust.
                return self._fallback(current, objective, sense, "CERTIFIED_NO_PROVABLE_STEP", cert)
            else:
                return self._fallback(current, objective, sense, "CERTIFIED_HARMFUL", cert)
        if self.mode == "prior" and self.prior_sign is not None:
            ps = self.prior_sign(a, objective)
            if ps is not None and d * ps == sense:
                nxt = dict(current); nxt[a] = float(np.clip(current[a] + step, LO, HI))
                return GateDecision("ACCEPT", "PRIOR_BENEFICIAL", nxt, cert)
            return self._fallback(current, objective, sense, "PRIOR_HARMFUL", cert)
        if self.mode == "trust":
            if self.budget + 1e-9 >= self.cautious_step:
                small = float(np.clip(step, -self.cautious_step, self.cautious_step))
                nxt = dict(current); nxt[a] = float(np.clip(current[a] + small, LO, HI))
                self.budget -= abs(nxt[a] - current[a])
                self.pending.append((a, d, objective))
                return GateDecision("ACCEPT", "UNCERTIFIED_TRUSTED", nxt, cert)
            return self._fallback(current, objective, sense, "UNCERTIFIED", cert)
        if self.mode == "cautious":
            small = float(np.clip(step, -self.cautious_step, self.cautious_step))
            nxt = dict(current); nxt[a] = float(np.clip(current[a] + small, LO, HI))
            return GateDecision("ACCEPT", "UNCERTIFIED_CAUTIOUS", nxt, cert)
        return self._fallback(current, objective, sense, "UNCERTIFIED", cert)


